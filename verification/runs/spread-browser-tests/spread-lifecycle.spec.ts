import {test,expect} from '../../../frontend/node_modules/@playwright/test/index.mjs';
import {writeFile} from 'node:fs/promises';
test('cancel and resume the same original qualification, then reopen it from saved history',async({page},info)=>{
  test.setTimeout(180000);await page.goto('/');await page.waitForLoadState('networkidle');
  const nav=page.getByRole('navigation',{name:'Research sections'});
  await nav.getByRole('button',{name:/^(03 )?Experiments$/}).click();
  await page.getByRole('combobox',{name:'Dataset',exact:true}).selectOption(process.env.PA_SPREAD_DATASET!);
  await page.getByLabel('Start date',{exact:true}).fill('2026-10-19');await page.getByLabel('End date',{exact:true}).fill('2026-10-30');
  const form=page.getByRole('region',{name:'Balanced spread workflow',exact:true});
  await form.getByRole('button',{name:'Use small functional run',exact:true}).click();
  await form.getByLabel('Spread primary instrument',{exact:true}).selectOption('QQQ');
  await form.getByLabel('Spread proposals per batch',{exact:true}).fill('10');
  await form.getByLabel('Spread maximum batches per family',{exact:true}).fill('1');
  await form.getByRole('button',{name:'Preview spread work',exact:true}).click();
  const created=page.waitForResponse(r=>r.url().endsWith('/api/spreads')&&r.request().method()==='POST');
  await form.getByRole('button',{name:'Freeze and qualify spread',exact:true}).click();const parent=await(await created).json();
  await form.getByRole('button',{name:'Cancel spread qualification',exact:true}).click();
  await expect.poll(async()=>{const r=await(await page.request.get('/api/spreads/'+parent.id)).json();return r.job.status;},{timeout:45000}).toBe('canceled');
  const canceled=await(await page.request.get('/api/spreads/'+parent.id)).json();
  await expect(form.getByRole('button',{name:'Resume original spread qualification',exact:true})).toBeVisible({timeout:15000});
  await form.getByRole('button',{name:'Resume original spread qualification',exact:true}).click();
  await expect.poll(async()=>{const r=await(await page.request.get('/api/spreads/'+parent.id)).json();return r.job.status+':'+r.spread.stage;},{timeout:120000}).toBe('completed:exhausted');
  const complete=await(await page.request.get('/api/spreads/'+parent.id)).json();
  expect(complete.job.id).toBe(parent.id);expect(complete.job.payload_sha256).toBe(canceled.job.payload_sha256);expect(complete.account_job).toBeNull();
  await nav.getByRole('button',{name:/^(04 )?Results$/}).click();
  await page.getByRole('combobox',{name:'Completed job',exact:true}).selectOption(parent.id);
  await expect(page.getByRole('heading',{name:'Experiments',exact:true})).toBeVisible();
  await expect(form.getByLabel('Saved spread progress')).toContainText(parent.id);
  await expect(form).toContainText('The frozen budget was exhausted.');
  await form.screenshot({path:info.outputPath('spread-canceled-resumed-history.png')});
  await writeFile(info.outputPath('spread-cancel-resume-originals.json'),JSON.stringify({canceled,complete,scope:'Actual UI/API worker cancellation and original resume; flat primary, no financial accounts.'},null,2));
});
